#!/usr/bin/env python3
"""
Euclidean rhythms: G. T. Toussaint, "The Euclidean algorithm generates traditional musical
rhythms", Proceedings of BRIDGES: Mathematical Connections in Art, Music and Science (2005)
47-56 (cgm.cs.mcgill.ca/~godfried/publications/banff.pdf).

E(k, n): k onsets spread as evenly as possible over n pulses, generated by Bjorklund's
algorithm (which has the structure of Euclid's algorithm). Checked here:

1. Bjorklund's algorithm gives every rhythm of the paper's list (Sect. 4) exactly as
   printed there, in box notation.
2. The paper's classification (Sect. 5): which of them are Euclidean strings (Ellis et al.
   2003), reverse Euclidean strings, or neither.
3. EvoMaxx's drums use the closed form "step s is an onset when (s k) mod n < k": it gives
   a rotation of the same necklace, for every k <= n <= 32.

  ./euclid.py           results/euclid.json, results/fig1_necklaces.png
"""
import json
from pathlib import Path

RESULTS = Path(__file__).resolve().parent / "results"

# Sect. 4 of the paper, in its box notation (x: onset, .: rest)
PAPER = {
    (2, 5): "x . x . .", (3, 4): "x . x x", (3, 5): "x . x . x", (3, 7): "x . x . x . .", (3, 8): "x . . x . . x .",
    (4, 7): "x . x . x . x", (4, 9): "x . x . x . x . .", (4, 11): "x . . x . . x . . x .", (5, 6): "x . x x x x",
    (5, 7): "x . x x . x x", (5, 8): "x . x x . x x .", (5, 9): "x . x . x . x . x", (5, 11): "x . x . x . x . x . .",
    (5, 12): "x . . x . x . . x . x .", (5, 16): "x . . x . . x . . x . . x . . . .", (7, 8): "x . x x x x x x",
    (7, 12): "x . x x . x . x x . x .", (7, 16): "x . . x . x . x . . x . x . x .",
    (9, 16): "x . x x . x . x . x x . x . x .", (11, 24): "x . . x . x . x . x . x . . x . x . x . x . x .",
    (13, 24): "x . x x . x . x . x . x . x x . x . x . x . x .",
}
# Sect. 5: Euclidean strings, reverse Euclidean strings, and neither
PAPER_STRINGS = {"euclidean": [(2, 5), (3, 7), (4, 9), (5, 11), (5, 16)],
                 "reverse": [(2, 3), (3, 4), (3, 5), (3, 8), (4, 7), (4, 11), (5, 6), (5, 7), (5, 9), (5, 12), (7, 8), (7, 16), (11, 24)],
                 "neither": [(5, 8), (7, 12), (9, 16), (13, 24)]}


def bjorklund(k, n):
    """Bjorklund's algorithm as the paper performs it (Sect. 3): k groups [1] and n - k
    groups [0]; repeatedly append one remainder group to each leading group, the unpaired
    groups becoming the new remainder, until at most one remainder group is left (the first
    pairing always happens). Concatenating the groups gives the rhythm."""
    groups, rest = [[1] for _ in range(k)], [[0] for _ in range(n - k)]
    while rest and groups:
        pairs = min(len(groups), len(rest))
        groups, rest = [groups[i] + rest[i] for i in range(pairs)], groups[pairs:] or rest[pairs:]
        if len(rest) <= 1:
            break
    return [b for g in groups + rest for b in g]


def box(pattern):
    return " ".join("x" if b else "." for b in pattern)


def intervals(pattern):
    """The inter-onset interval vector, e.g. x . x . . -> (2, 3)."""
    onsets = [i for i, b in enumerate(pattern) if b]
    n = len(pattern)
    return [(onsets[(i + 1) % len(onsets)] - onsets[i]) % n or n for i in range(len(onsets))]


def is_rotation(a, b):
    return len(a) == len(b) and any(a == b[i:] + b[:i] for i in range(len(b)))


def euclidean_string(p):
    """Ellis et al.: P is a Euclidean string if tau(P) (p0 + 1, p_last - 1) is a rotation of P."""
    if len(p) == 1:
        return True
    t = [p[0] + 1] + p[1:-1] + [p[-1] - 1]
    return is_rotation(t, p)


def evomaxx(k, n):
    """The closed form used by EvoMaxx's Euclidean drums."""
    return [1 if (s * k) % n < k else 0 for s in range(n)]


def main():
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    import numpy as np
    RESULTS.mkdir(exist_ok=True)
    report = {"rhythms": {}, "classification": {}, "evomaxx": {}}
    exact = 0
    for (k, n), printed in PAPER.items():
        made = box(bjorklund(k, n))
        exact += made == printed
        report["rhythms"][f"E({k},{n})"] = {"paper": printed, "bjorklund": made, "same": made == printed}
        if made != printed:
            print(f"E({k},{n}): paper {printed} | Bjorklund {made}")
    print(f"Bjorklund reproduces {exact} of {len(PAPER)} rhythms of the paper exactly")

    agree = 0
    for group, members in PAPER_STRINGS.items():
        for k, n in members:
            iv = intervals(bjorklund(k, n))
            mine = "euclidean" if euclidean_string(iv) else "reverse" if euclidean_string(iv[::-1]) else "neither"
            agree += mine == group
            report["classification"][f"E({k},{n})"] = {"intervals": iv, "paper": group, "here": mine}
            if mine != group:
                print(f"E({k},{n}) {iv}: paper {group}, here {mine}")
    total = sum(len(v) for v in PAPER_STRINGS.values())
    print(f"classification agrees for {agree} of {total} rhythms")

    rotations = sum(is_rotation(evomaxx(k, n), bjorklund(k, n)) for n in range(1, 33) for k in range(0, n + 1))
    pairs = sum(1 for n in range(1, 33) for k in range(0, n + 1))
    report["evomaxx"] = {"rotations_of_bjorklund": rotations, "pairs": pairs}
    print(f"EvoMaxx's closed form is a rotation of Bjorklund's rhythm for {rotations} of {pairs} (k, n) with n <= 32")

    shown = [(3, 8), (5, 8), (7, 12), (5, 16), (7, 16), (9, 16)]
    fig, axes = plt.subplots(1, len(shown), figsize=(15, 2.9))
    for ax, (k, n) in zip(axes, shown):
        p = bjorklund(k, n); a = np.pi / 2 - 2 * np.pi * np.arange(n) / n
        ax.plot(np.cos(a), np.sin(a), color="#999", lw=0.8)
        on = [i for i in range(n) if p[i]]
        ax.fill(np.cos(a[on]), np.sin(a[on]), color="#ffcf6e", alpha=0.6)
        ax.scatter(np.cos(a), np.sin(a), c=["#c03030" if b else "white" for b in p], edgecolors="k", s=60, zorder=3)
        ax.set_title(f"E({k},{n})", fontsize=11); ax.set_aspect("equal"); ax.axis("off")
    fig.suptitle("Euclidean rhythms as necklaces (clockwise from the top)")
    fig.tight_layout(); fig.savefig(RESULTS / "fig1_necklaces.png", dpi=110); plt.close(fig)
    (RESULTS / "euclid.json").write_text(json.dumps(report, indent=1))


if __name__ == "__main__":
    main()
